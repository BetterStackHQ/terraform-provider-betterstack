package provider

// SmokeFixture is one managed resource's sample inputs: what the generated acceptance suite
// creates, updates and replaces against the mock API, as attribute values rather than HCL so a
// bridge (see pkg/apitest) can run the same matrix through its own surface. Values are JSON-shaped:
// strings, ints, float64s, bools, []interface{} and map[string]interface{}.
type SmokeFixture struct {
	// Resource is the binding's name: the Terraform type without the provider prefix.
	Resource string
	TFType   string
	// Create, Update and Replace map Terraform attribute names to values. Update is nil when the
	// resource has no updatable input to exercise, Replace when it has no create-only one.
	Create  map[string]interface{}
	Update  map[string]interface{}
	Replace map[string]interface{}
	// Seed is set for resources the provider adopts rather than creates: the record must exist
	// before the first apply.
	Seed *SmokeSeed
	// Settle is what the API shows once a create's work is done (a status of running): the mock must
	// assign it on create (InjectOnCreate), or the provider waits for it.
	Settle map[string]interface{}
	// ComputedItemFields are server-assigned fields the mock adds to every item of a dynamic
	// collection input, keyed by the input's name. ComputedChecks are the Terraform attribute
	// paths (flatmap notation) where they surface after apply, with the value expected there.
	ComputedItemFields map[string]map[string]interface{}
	ComputedChecks     map[string]string
	// WriteOnly inputs never come back from the API. DynamicInputs are collections whose read-back
	// lands in a separate result attribute. Neither round-trips through import verbatim.
	WriteOnly     []string
	DynamicInputs []string
	// ImportParts are the attributes a composite import id is assembled from, in order.
	ImportParts []string
}

// SmokeSeed is the record an adopting resource expects to find: its id and the parent path
// variables scoping its collection.
type SmokeSeed struct {
	Resource string
	Vars     map[string]string
	ID       string
}

